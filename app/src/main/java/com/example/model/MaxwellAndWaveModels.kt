enum class MaxwellLawType(
  val title: String,
  val shortName: String,
  val differentialForm: String,
  val integralForm: String,
  val primaryPhysicalConcept: String
) {
  GAUSS_ELECTRIC(
    title = "Gauss's Law for Electricity",
    shortName = "Gauss Electric",
    differentialForm = "∇ · D = ρ_v",
    integralForm = "∮_S D · dA = Q_enclosed",
    primaryPhysicalConcept = "Electric charges are the sources and sinks of electric fields. Total electric flux through any closed surface is proportional to enclosed net charge."
  ),
  GAUSS_MAGNETIC(
    title = "Gauss's Law for Magnetism",
    shortName = "Gauss Magnetic",
    differentialForm = "∇ · B = 0",
    integralForm = "∮_S B · dA = 0",
    primaryPhysicalConcept = "There are no isolated magnetic monopoles in classical electrodynamics. Magnetic field lines always form closed continuous loops; net magnetic flux through any closed surface is identically zero."
  ),
  FARADAY(
    title = "Faraday's Law of Electromagnetic Induction",
    shortName = "Faraday's Law",
    differentialForm = "∇ × E = -∂B/∂t",
    integralForm = "∮_C E · dl = -dΦ_B/dt",
    primaryPhysicalConcept = "A time-varying magnetic field induces a circulating, non-conservative electric field. The negative sign (Lenz's Law) enforces energy conservation by opposing the flux change."
  ),
  AMPERE_MAXWELL(
    title = "Ampère-Maxwell Circuital Law",
    shortName = "Ampère-Maxwell",
    differentialForm = "∇ × H = J_c + ∂D/∂t",
    integralForm = "∮_C H · dl = I_c + dΦ_D/dt",
    primaryPhysicalConcept = "Magnetic fields are generated by both conduction electric currents (J_c) and time-varying electric flux (Maxwell's displacement current ∂D/∂t), enabling self-sustaining electromagnetic wave propagation."
  )
}

data class WaveMedium(
  val name: String,
  val relativePermittivity: Double,
  val relativePermeability: Double = 1.0,
  val conductivitySiemensPerMeter: Double = 0.0 // Lossless assumed for standard plane waves
) {
  val waveSpeedMetersPerSec: Double
    get() = 1.0 / kotlin.math.sqrt(relativePermittivity * PhysicsConstants.EPSILON_0 * relativePermeability * PhysicsConstants.MU_0)

  val refractiveIndex: Double
    get() = PhysicsConstants.C / waveSpeedMetersPerSec

  val intrinsicImpedanceOhms: Double
    get() = kotlin.math.sqrt((relativePermeability * PhysicsConstants.MU_0) / (relativePermittivity * PhysicsConstants.EPSILON_0))
}

